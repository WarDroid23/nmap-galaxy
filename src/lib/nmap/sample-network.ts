function ports(...rows: [number, "tcp" | "udp", string, string?][]): PortRecord[] {
  return rows.map(([port, proto, service, version]) => ({
    port,
    proto,
    state: "open" as const,
    service,
    version,
  }));
}

function node(
  partial: Omit<GraphNode, "findings" | "status" | "latencyMs" | "mac"> &
    Partial<Pick<GraphNode, "findings" | "status" | "latencyMs" | "mac">>,
): GraphNode {
  return {
    status: "up",
    latencyMs: 1 + (partial.id.charCodeAt(0) % 9) + (partial.id.length % 5),
    findings: [],
    mac: partial.mac,
    ...partial,
  };
}

